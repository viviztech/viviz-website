export const WEBSITE_PACKAGE_PAYMENTS = {
  starter: {
    id: "starter",
    name: "Starter Website",
    amount: 9_999,
  },
  growth: {
    id: "growth",
    name: "Business Growth",
    amount: 24_999,
  },
  ecommerce: {
    id: "ecommerce",
    name: "E-commerce",
    amount: 44_999,
  },
} as const;

export type WebsitePackageId = keyof typeof WEBSITE_PACKAGE_PAYMENTS;
export type WebsitePackagePayment = (typeof WEBSITE_PACKAGE_PAYMENTS)[WebsitePackageId];

export function getWebsitePackagePayment(value: unknown): WebsitePackagePayment | null {
  if (typeof value !== "string" || !(value in WEBSITE_PACKAGE_PAYMENTS)) return null;
  return WEBSITE_PACKAGE_PAYMENTS[value as WebsitePackageId];
}
